/**
 * Cross-language receipt digest regression tests (P-27.06 eighth-run repair).
 *
 * ROOT CAUSE (verified live, run_d82ee30a, 2026-10-22): the trusted Python bridge
 * computed receipt digests over `build_canonical_public_receipt_payload`, which
 * SORTS the `disclaimers` / `not_run_obligations` / `runtime_identities` list
 * fields and distinguishes Python ints from floats, while the wire receipt
 * (`to_dict()`) preserved insertion order and integral-valued floats (`0.0`,
 * `30.0`). ECMAScript `JSON.parse` collapses `0.0` and `0` into the same number,
 * so the Worker could never recompute a genuine Python bridge receipt digest and
 * every COMPLETED live run failed import with "Receipt digest verification
 * failed." The JS test fixtures were built in JS (already-sorted lists, integer
 * numbers), which kept the defect invisible to the Node suite.
 *
 * REPAIR: the Python wire receipt now serializes the canonical payload exactly
 * (sorted lists, integral floats normalized to portable ints), and the JS
 * canonicalization mirrors the Python normalization (sorted list fields,
 * lowercased digest-like fields, ensure_ascii-compatible string escaping).
 *
 * The committed fixture below is generated by
 * `test/fixtures/generate_python_receipt_fixture.py` using the production
 * Python receipt factory with deliberately UNSORTED list inputs,
 * integral-valued floats (timeout_seconds=30.0, coverage_ratio=1.0,
 * coverage_percentage=100.0), and non-ASCII characters. Provenance: FIXTURE /
 * LOCAL_EXECUTION only.
 */

import { describe, it } from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import url from "node:url";
import {
  canonicalJson,
  computeReceiptDigest,
  verifyReceiptIntegrity,
} from "../src/crypto_utils.js";

const __dirname = path.dirname(url.fileURLToPath(import.meta.url));
const fixturePath = path.join(
  __dirname,
  "fixtures",
  "python_public_receipt_fixture.json"
);
const receipt = JSON.parse(
  fs.readFileSync(fixturePath, "utf8").replace(/^\uFEFF/, "")
);

describe("Cross-language receipt digest (Python-built fixture)", () => {
  it("recomputes the Python-declared receipt digest exactly", () => {
    assert.equal(typeof receipt.receipt_digest, "string");
    assert.match(receipt.receipt_digest, /^[0-9a-f]{64}$/);
    assert.equal(computeReceiptDigest(receipt), receipt.receipt_digest);
    assert.equal(verifyReceiptIntegrity(receipt), true);
  });

  it("exercises integral-valued floats and unsorted Python inputs", () => {
    // The fixture must genuinely cover the historical failure modes.
    assert.equal(receipt.coverage_summary.coverage_percentage, 100);
    assert.equal(receipt.coverage_summary.coverage_ratio, 1);
    assert.equal(receipt.witnesses[0].timeout_seconds, 30);
    const identities = receipt.runtime_identities;
    assert.deepEqual([...identities].sort(), identities);
    assert.notEqual(
      identities[0],
      "zzz-identity-last",
      "fixture input order was unsorted; wire must be canonically sorted"
    );
    const disclaimers = receipt.disclaimers;
    assert.deepEqual([...disclaimers].sort(), disclaimers);
    assert.ok(
      disclaimers.some((d) => /[^\x00-\x7f]/.test(d) || /\\u[0-9a-f]{4}/.test(d)),
      "fixture must include non-ASCII content"
    );
  });

  it("still rejects tampered receipts", () => {
    const tamperedIdentity = structuredClone(receipt);
    tamperedIdentity.runtime_identities = [
      "aaa-identity-first",
      "INJECTED",
      "mmm-identity-middle",
    ];
    assert.equal(verifyReceiptIntegrity(tamperedIdentity), false);

    const tamperedCoverage = structuredClone(receipt);
    tamperedCoverage.coverage_summary.coverage_percentage = 50;
    assert.equal(verifyReceiptIntegrity(tamperedCoverage), false);

    const tamperedTree = structuredClone(receipt);
    tamperedTree.candidate_tree_digest = "f".repeat(40);
    assert.equal(verifyReceiptIntegrity(tamperedTree), false);

    const tamperedDisclaimer = structuredClone(receipt);
    tamperedDisclaimer.disclaimers.push("extra disclaimer");
    assert.equal(verifyReceiptIntegrity(tamperedDisclaimer), false);

    const tamperedVerdict = structuredClone(receipt);
    tamperedVerdict.overall_verdict = "INCONCLUSIVE";
    assert.equal(verifyReceiptIntegrity(tamperedVerdict), false);
  });

  it("canonicalJson escapes non-ASCII exactly like Python ensure_ascii", () => {
    assert.equal(canonicalJson("çğıöşü"), '"\\u00e7\\u011f\\u0131\\u00f6\\u015f\\u00fc"');
    assert.equal(canonicalJson("\u007f"), '"\\u007f"');
    assert.equal(canonicalJson("plain"), '"plain"');
    assert.equal(canonicalJson("tab\tnewline\n"), '"tab\\tnewline\\n"');
  });
});
